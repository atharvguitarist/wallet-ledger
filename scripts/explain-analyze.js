'use strict';

/*
 * EXPLAIN ANALYZE for the reconciliation checks, statement pagination
 * (OFFSET 100000 vs cursor) and the fraud-rule queries.
 *
 * Expects a big seeded database, e.g.:
 *   npm run seed -- --reset --users 2000 --wallets 4000 --transfers 380000
 *   npm run perf:explain > docs/performance-plans.md
 *
 * If no wallet has at least 120,000 ledger entries yet, it first creates one
 * "hot" wallet with 120,000 outgoing transfers so OFFSET 100000 is meaningful.
 */

const { pool } = require('../src/db');
const { CHECKS } = require('../src/services/reconciliation');
const { BASE_SELECT } = require('../src/services/statement');
const { postEntriesForNewTransfers } = require('./seed');

const HOT_ENTRIES = 120000;

async function ensureHotWallet() {
  const { rows } = await pool.query(
    `SELECT a.id FROM accounts a
      WHERE a.kind = 'user_wallet'
        AND (SELECT count(*) FROM ledger_entries le WHERE le.account_id = a.id) >= $1
      LIMIT 1`,
    [HOT_ENTRIES]
  );
  if (rows[0]) return rows[0].id;

  const client = await pool.connect();
  try {
    await client.query("SELECT set_config('app.actor', 'perf-seed', false)");
    await client.query('BEGIN');
    const { rows: [u] } = await client.query(
      `INSERT INTO users (name, email, phone, kyc_status) VALUES ('Hot Wallet', 'hot.wallet@perf.dev', '+915550000001', 'verified') RETURNING id`
    );
    const { rows: [w] } = await client.query(`INSERT INTO accounts (kind, user_id, name) VALUES ('user_wallet', $1, 'main') RETURNING id`, [u.id]);
    const cashIn = (await client.query(`SELECT id FROM accounts WHERE system_code = 'cash_in'`)).rows[0].id;
    await client.query(
      `INSERT INTO transfers (type, status, amount, source_account_id, destination_account_id, note, created_at)
       VALUES ('topup', 'completed', 100000000000, $1, $2, 'perf funding', now() - interval '95 days')`,
      [cashIn, w.id]
    );
    await client.query(
      `INSERT INTO transfers (type, status, amount, source_account_id, destination_account_id, note, created_at)
       SELECT 'p2p', 'completed', 100 + (g % 5000), $1,
              (SELECT id FROM accounts WHERE kind = 'user_wallet' AND id <> $1 ORDER BY id LIMIT 1 OFFSET (g % 500)),
              'perf', now() - (g || ' seconds')::interval
         FROM generate_series(1, $2::int) g`,
      [w.id, HOT_ENTRIES]
    );
    await postEntriesForNewTransfers(client);
    await client.query(
      `UPDATE accounts a SET balance = c.b FROM (
         SELECT account_id, SUM(CASE WHEN direction = 'credit' THEN amount ELSE -amount END)::bigint AS b
           FROM ledger_entries GROUP BY account_id) c
        WHERE c.account_id = a.id AND a.balance <> c.b`
    );
    await client.query('COMMIT');
    await client.query('ANALYZE');
    return w.id;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

async function explain(title, sql, params = []) {
  const { rows } = await pool.query(`EXPLAIN (ANALYZE, BUFFERS, COSTS OFF) ${sql}`, params);
  const plan = rows.map((r) => r['QUERY PLAN']).join('\n');
  const time = plan.match(/Execution Time: ([\d.]+) ms/);
  console.log(`### ${title}\n`);
  console.log('```');
  console.log(plan);
  console.log('```\n');
  return time ? Number(time[1]) : null;
}

async function main() {
  const hot = await ensureHotWallet();
  const { rows: [size] } = await pool.query(
    `SELECT (SELECT count(*) FROM ledger_entries) AS entries, (SELECT count(*) FROM transfers) AS transfers,
            (SELECT count(*) FROM ledger_entries WHERE account_id = $1) AS hot_entries, current_setting('server_version') AS v`,
    [hot]
  );
  console.log(`<!-- generated by scripts/explain-analyze.js -->`);
  console.log(`Database: ${size.entries.toLocaleString('en-IN')} ledger entries, ${size.transfers.toLocaleString('en-IN')} transfers, PostgreSQL ${size.v}. Hot wallet ${hot} has ${size.hot_entries.toLocaleString('en-IN')} entries.\n`);
  const timings = [];

  console.log('## Reconciliation checks\n');
  for (const [name, sql] of Object.entries(CHECKS)) timings.push([`recon: ${name}`, await explain(`Check: ${name}`, sql)]);

  console.log('## Statement pagination on the hot wallet\n');
  timings.push(['statement page 1 (offset 0)', await explain('Page 1: LIMIT 20 OFFSET 0', `${BASE_SELECT} WHERE le.account_id = $1 ORDER BY le.created_at DESC, le.id DESC LIMIT 20 OFFSET 0`, [hot])]);
  timings.push(['statement OFFSET 100000', await explain('Deep page: LIMIT 20 OFFSET 100000', `${BASE_SELECT} WHERE le.account_id = $1 ORDER BY le.created_at DESC, le.id DESC LIMIT 20 OFFSET 100000`, [hot])]);
  const { rows: [c] } = await pool.query(
    `SELECT created_at::text AS t, id FROM ledger_entries WHERE account_id = $1 ORDER BY created_at DESC, id DESC OFFSET 99999 LIMIT 1`,
    [hot]
  );
  timings.push(['statement cursor at row 100000', await explain('Same deep page with a cursor: WHERE (created_at, id) < (...) LIMIT 20',
    `${BASE_SELECT} WHERE le.account_id = $1 AND (le.created_at, le.id) < ($2::timestamptz, $3::bigint) ORDER BY le.created_at DESC, le.id DESC LIMIT 20`,
    [hot, c.t, c.id])]);

  console.log('## Fraud-rule queries (run inside every transfer)\n');
  timings.push(['rule velocity', await explain('velocity', `SELECT count(*) FROM transfers WHERE source_account_id = $1 AND created_at > now() - make_interval(secs => 60)`, [hot])]);
  timings.push(['rule daily_limit', await explain('daily_limit', `SELECT COALESCE(SUM(amount), 0) FROM transfers WHERE source_account_id = $1 AND status IN ('completed','held') AND created_at > now() - make_interval(secs => 86400)`, [hot])]);
  const { rows: [peer] } = await pool.query(`SELECT destination_account_id AS d FROM transfers WHERE source_account_id = $1 LIMIT 1`, [hot]);
  timings.push(['rule new_payee_large', await explain('new_payee_large', `SELECT EXISTS (SELECT 1 FROM transfers WHERE source_account_id = $1 AND destination_account_id = $2 AND status = 'completed')`, [hot, peer.d])]);

  console.log('## Summary\n');
  console.log('| Query | Execution time (ms) |');
  console.log('|---|---:|');
  for (const [name, ms] of timings) console.log(`| ${name} | ${ms} |`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => pool.end());
