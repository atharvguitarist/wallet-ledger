'use strict';

/*
 * Milestone 2, Step 1 — the two-session isolation lab, automated.
 *
 * Opens two separate PostgreSQL connections ("session A" and "session B"),
 * runs the four cases from the brief step by step, and prints a transcript in
 * markdown (docs/isolation.md was produced with this script). Every SQL line
 * is exactly what you would type into two psql windows side by side.
 *
 * It works in a throw-away schema "isolation_lab" so the real ledger is never
 * touched.   Run:  npm run lab:isolation
 */

const { Client } = require('pg');
const config = require('../src/config');

const out = [];
const log = (s = '') => out.push(s);

function table(rows) {
  if (!rows || !rows.length) return '(0 rows)';
  const cols = Object.keys(rows[0]);
  const width = cols.map((c) => Math.max(c.length, ...rows.map((r) => String(r[c]).length)));
  const line = (vals) => ` ${vals.map((v, i) => String(v).padEnd(width[i])).join(' | ')}`;
  return [line(cols), `-${width.map((w) => '-'.repeat(w)).join('-+-')}-`, ...rows.map((r) => line(cols.map((c) => r[c])))].join('\n');
}

async function run(session, label, sql) {
  log(`${label}=> ${sql}`);
  try {
    const res = await session.query(sql);
    if (res.command === 'SELECT') log(table(res.rows));
    else log(res.command);
    return res;
  } catch (err) {
    log(`ERROR:  ${err.message}`);
    return null;
  }
}

async function setup(admin) {
  await admin.query(`
    DROP SCHEMA IF EXISTS isolation_lab CASCADE;
    CREATE SCHEMA isolation_lab;
    CREATE TABLE isolation_lab.users   (id BIGINT PRIMARY KEY, name TEXT NOT NULL);
    CREATE TABLE isolation_lab.wallets (id BIGINT PRIMARY KEY, user_id BIGINT REFERENCES isolation_lab.users, balance BIGINT NOT NULL CHECK (balance >= 0));
    INSERT INTO isolation_lab.users   VALUES (1, 'Asha'), (2, 'Rahul');
    INSERT INTO isolation_lab.wallets VALUES (10, 1, 50000), (20, 2, 30000);`);
}

async function main() {
  const A = new Client({ connectionString: config.databaseUrl });
  const B = new Client({ connectionString: config.databaseUrl });
  await A.connect();
  await B.connect();
  await A.query('SET search_path = isolation_lab');
  await B.query('SET search_path = isolation_lab');
  const reset = () => setup(A);
  const v = (await A.query('SHOW server_version')).rows[0].server_version;

  log(`<!-- generated by scripts/isolation-lab.js against PostgreSQL ${v} -->`);
  log('Setup (both sessions): `SET search_path = isolation_lab;` wallets 10 (Asha, ₹500 = 50000 paise) and 20 (Rahul, ₹300).');
  log();

  // ---------------------------------------------------------------- case 1
  await reset();
  log('### Case 1 — Read Committed (the Postgres default)');
  log('```');
  await run(A, 'A', 'BEGIN;  -- READ COMMITTED');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;');
  await run(B, 'B', 'UPDATE wallets SET balance = balance - 10000 WHERE id = 10;');
  log('B=> -- (autocommit: committed immediately)');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;');
  await run(A, 'A', 'COMMIT;');
  log('```');
  log('**Result:** yes — session A sees a different value (50000, then 40000) inside the same transaction. Each statement in Read Committed takes a fresh snapshot: a *non-repeatable read*.');
  log();

  // ---------------------------------------------------------------- case 2
  await reset();
  log('### Case 2 — Repeatable Read');
  log('```');
  await run(A, 'A', 'BEGIN ISOLATION LEVEL REPEATABLE READ;');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;');
  await run(B, 'B', 'UPDATE wallets SET balance = balance - 10000 WHERE id = 10;');
  log('B=> -- committed');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;');
  log('A=> -- now try to write based on what A read:');
  await run(A, 'A', 'UPDATE wallets SET balance = balance - 5000 WHERE id = 10;');
  await run(A, 'A', 'ROLLBACK;');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;  -- outside any transaction');
  log('```');
  log('**Result:** session A keeps seeing 50000 for the whole transaction: its snapshot is taken at the first query and never moves. When A then tries to update the row that B changed, Postgres refuses with *could not serialize access due to concurrent update* (SQLSTATE 40001) instead of silently losing B\'s update. The application must retry.');
  log();

  // ---------------------------------------------------------------- case 3
  await reset();
  log('### Case 3 — Serializable: both sessions read a balance, then write based on it');
  log('```');
  await run(A, 'A', 'BEGIN ISOLATION LEVEL SERIALIZABLE;');
  await run(B, 'B', 'BEGIN ISOLATION LEVEL SERIALIZABLE;');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;');
  await run(B, 'B', 'SELECT balance FROM wallets WHERE id = 10;');
  log('A=> -- A spends ₹100: 50000 - 10000');
  await run(A, 'A', 'UPDATE wallets SET balance = 40000 WHERE id = 10;');
  log('B=> -- B also spends ₹100 based on the 50000 it read (this statement blocks on A\'s row lock...)');
  log('B=> UPDATE wallets SET balance = 40000 WHERE id = 10;');
  const pending = B.query('UPDATE wallets SET balance = 40000 WHERE id = 10;').then(
    (r) => `${r.command}`,
    (err) => `ERROR:  ${err.message}  (SQLSTATE ${err.code})`
  );
  await new Promise((r) => setTimeout(r, 300));
  log('B   ...waiting...');
  await run(A, 'A', 'COMMIT;');
  log(`B   ${await pending}`);
  await run(B, 'B', 'ROLLBACK;');
  await run(A, 'A', 'SELECT balance FROM wallets WHERE id = 10;');
  log('```');
  log('**Result:** one of them fails. B waits for A\'s row lock; when A commits, B is aborted with SQLSTATE 40001. Without that error B would have written 40000 too and one ₹100 spend would vanish (a lost update). Serializable makes this safe, but the losing transaction must be retried by the application.');
  log();

  // ------------------------------------------------------- case 3b (bonus)
  await reset();
  log('#### Case 3b (bonus) — Serializable catches write skew on *different* rows');
  log('Rule: Asha + Rahul together must keep at least ₹700. Each session checks the total, then debits a *different* wallet.');
  log('```');
  await run(A, 'A', 'BEGIN ISOLATION LEVEL SERIALIZABLE;');
  await run(B, 'B', 'BEGIN ISOLATION LEVEL SERIALIZABLE;');
  await run(A, 'A', 'SELECT sum(balance) AS total FROM wallets;');
  await run(B, 'B', 'SELECT sum(balance) AS total FROM wallets;');
  await run(A, 'A', 'UPDATE wallets SET balance = balance - 10000 WHERE id = 10;');
  await run(B, 'B', 'UPDATE wallets SET balance = balance - 10000 WHERE id = 20;');
  await run(A, 'A', 'COMMIT;');
  await run(B, 'B', 'COMMIT;');
  log('```');
  log('**Result:** no row was written twice, so row locks would not help — yet Serializable (SSI) still aborts the second commit with *could not serialize access due to read/write dependencies among transactions*. Repeatable Read would have let both commit and broken the ₹700 rule.');
  log();

  // ---------------------------------------------------------------- case 4
  await reset();
  log('### Case 4 — Repeatable Read with a join');
  log('```');
  await run(A, 'A', 'BEGIN ISOLATION LEVEL REPEATABLE READ;');
  await run(A, 'A', 'SELECT u.name, w.balance FROM wallets w JOIN users u ON u.id = w.user_id WHERE w.id = 10;');
  await run(B, 'B', 'BEGIN;');
  await run(B, 'B', "UPDATE users SET name = 'Asha V.' WHERE id = 1;");
  await run(B, 'B', 'UPDATE wallets SET balance = balance - 10000 WHERE id = 10;');
  await run(B, 'B', 'COMMIT;');
  await run(A, 'A', 'SELECT u.name, w.balance FROM wallets w JOIN users u ON u.id = w.user_id WHERE w.id = 10;');
  await run(A, 'A', 'COMMIT;');
  await run(A, 'A', 'SELECT u.name, w.balance FROM wallets w JOIN users u ON u.id = w.user_id WHERE w.id = 10;');
  log('```');
  log('**Result:** yes, the guarantee holds across the join. The snapshot belongs to the *transaction*, not to a table, so every table in every query sees the database as of A\'s first statement. Only after COMMIT does A see "Asha V." and 40000.');

  await A.query('DROP SCHEMA isolation_lab CASCADE');
  await A.end();
  await B.end();
  console.log(out.join('\n'));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
